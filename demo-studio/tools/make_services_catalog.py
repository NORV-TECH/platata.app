"""Copy the four demo trades' researched catalogue from the app into kit/services-data.js.

    python3 demo-studio/tools/make_services_catalog.py /path/to/suma-plus-android

Reads app/src/main/assets/catalogo_investigado/<trade>.json (peluqueria, veterinaria, taller-motos, unas)
and rewrites the block between /*CATALOG-START*/ and /*CATALOG-END*/ in kit/services-data.js, so the
service names (es/pt/en), categories, choices, included items, add-ons, minutes and Colombian prices are
exactly the app's. Products are NOT copied: the kit keeps its own generic product names (no brands).
"""
import json
import os
import re
import subprocess
import sys

TRADES = ["peluqueria", "veterinaria", "taller-motos", "unas"]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def txt(o):
    return {k: o.get(k, "") for k in ("es", "pt", "en")}


def main():
    app = sys.argv[1]
    head = subprocess.check_output(["git", "-C", app, "log", "-1", "--format=%h"], text=True).strip()
    out = {}
    for t in TRADES:
        d = json.load(open(os.path.join(app, "app/src/main/assets/catalogo_investigado", t + ".json"), encoding="utf-8"))
        cats = {c["id"]: txt(c) for c in d["categories"]}
        services = []
        for s in d["services"]:
            row = {"id": s["id"], "cat": s["category"], "n": txt(s["name"]), "st": bool(s.get("starter")),
                   "co": s.get("price_co"), "min": s.get("duration_min"), "ones": [], "inc": [], "add": []}
            for o in s.get("options", []):
                if o["type"] == "ESCOGER UNO":
                    row["ones"].append({"n": txt(o["name"]), "v": [
                        {"n": txt(v), "co": v.get("price_co"), "min": v.get("duration_min")} for v in o.get("values", [])]})
                elif o["type"] == "INCLUIDO":
                    row["inc"].append({"n": txt(o["name"]), "min": o.get("duration_min")})
                elif o["type"] == "COBRA MÁS":
                    row["add"].append({"n": txt(o["name"]), "co": o.get("amount"), "min": o.get("duration_min"),
                                       "per": o.get("per_unit")})
            services.append(row)
        out[t] = {"cats": cats, "services": services}
    block = "/*CATALOG-START*/\n/* generated by tools/make_services_catalog.py from catalogo_investigado at app commit " + head + " */\nconst CATALOG = " + \
        json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n/*CATALOG-END*/"
    path = os.path.join(ROOT, "kit", "services-data.js")
    src = open(path, encoding="utf-8").read()
    src = re.sub(r"/\*CATALOG-START\*/.*?/\*CATALOG-END\*/", lambda m: block, src, flags=re.S)
    open(path, "w", encoding="utf-8").write(src)
    print("catalogue written from", head, {t: len(out[t]["services"]) for t in TRADES})


if __name__ == "__main__":
    main()
